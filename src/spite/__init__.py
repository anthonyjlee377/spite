def check(S, n=None):
    """
    Checks if the input array matches the mandatory (Nf, N, N) shape.
    Optionally enforces a specific number of ports 'n' (e.g., n=1 or n=2).
    """
    S = np.asarray(S, dtype=complex)

    # Check dimensions
    if S.ndim != 3:
        raise ValueError(f"S-parameter array must be 3D with shape (Nf, N, N). Got {S.ndim}D shape: {S.shape}")

    # Check if it's a square matrix per frequency point
    if S.shape[1] != S.shape[2]:
        raise ValueError(f"S-parameter matrix must be square (Nf, N, N). Got shape: {S.shape}")

    # Check specific port count if requested
    if n is not None and S.shape[1] != n:
        raise ValueError(f"Expected a {n}-port network shape ({S.shape[0]}, {n}, {n}). Got: {S.shape}")

    return S

def check_network(f, S, n=None):
    """Validates both frequency vector and S-parameter matrix shapes together."""
    f = np.atleast_1d(np.asarray(f, dtype=float))
    S = check(S, n)

    if len(f) != S.shape[0]:
        raise ValueError(f"Frequency vector length ({len(f)}) must match S-parameter batch size ({S.shape[0]}).")

    return f, S


def S_to_Z(S, Z0=50):
    """Converts general (Nf, N, N) S-parameters to Z-parameters supporting multi-Z0 arrays."""
    S = check(S)
    Nf, N, _ = S.shape

    # Ensure Z0 is a 1D array of length N
    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(N, Z0_arr[0])

    #------------------------------------------------------------
    # 1-Port Vectorized Speed Override
    #------------------------------------------------------------
    if N == 1:
        S11 = S[:, 0, 0]
        Z_flat = Z0_arr[0] * (1.0 + S11) / (1.0 - S11)
        return Z_flat[:, np.newaxis, np.newaxis]

    #------------------------------------------------------------
    # 2-Port Vectorized Speed Override
    #------------------------------------------------------------
    elif N == 2:
        S11, S12, S21, S22 = S[:, 0, 0], S[:, 0, 1], S[:, 1, 0], S[:, 1, 1]
        Z01, Z02 = Z0_arr[0], Z0_arr[1]

        det = (1.0 - S11) * (1.0 - S22) - (S12 * S21)
        inv_00 = (1.0 - S22) / det
        inv_01 = S12 / det
        inv_10 = S21 / det
        inv_11 = (1.0 - S11) / det

        # Multi-Z0 algebraic matrix multiplication expansion
        Z = np.zeros_like(S, dtype=complex)
        Z[:, 0, 0] = Z01 * ((1.0 + S11) * inv_00 + S12 * inv_10)
        Z[:, 0, 1] = np.sqrt(Z01 * Z02) * ((1.0 + S11) * inv_01 + S12 * inv_11)
        Z[:, 1, 0] = np.sqrt(Z01 * Z02) * (S21 * inv_00 + (1.0 + S22) * inv_10)
        Z[:, 1, 1] = Z02 * (S21 * inv_01 + (1.0 + S22) * inv_11)
        return Z

    #------------------------------------------------------------
    # General N-Port LAPACK Fallback (N >= 3)
    #------------------------------------------------------------
    I = np.eye(N)
    mat_inv = np.linalg.inv(I - S)

    # Create the square-root impedance matrix block
    sqrt_Z0 = np.diag(np.sqrt(Z0_arr))

    # Z = sqrt(Z0) * (I + S) * (I - S)^-1 * sqrt(Z0)
    temp = np.matmul(I + S, mat_inv)
    return np.matmul(np.matmul(sqrt_Z0, temp), sqrt_Z0)

def Z_to_S(Z, Z0=50):
    """Converts general (Nf, N, N) Z-parameters to S-parameters supporting multi-Z0 arrays."""
    Z = check(Z)
    Nf, N, _ = Z.shape

    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(N, Z0_arr[0])

    #------------------------------------------------------------
    # 1-Port Vectorized Speed Override
    #------------------------------------------------------------
    if N == 1:
        Z11 = Z[:, 0, 0]
        S_flat = (Z11 - Z0_arr[0]) / (Z11 + Z0_arr[0])
        return S_flat[:, np.newaxis, np.newaxis]

    #------------------------------------------------------------
    # 2-Port Vectorized Speed Override
    #------------------------------------------------------------
    elif N == 2:
        Z11, Z12, Z21, Z22 = Z[:, 0, 0], Z[:, 0, 1], Z[:, 1, 0], Z[:, 1, 1]
        Z01, Z02 = Z0_arr[0], Z0_arr[1]

        # Scale parameters by independent port references
        z11 = Z11 / Z01
        z12 = Z12 / np.sqrt(Z01 * Z02)
        z21 = Z21 / np.sqrt(Z01 * Z02)
        z22 = Z22 / Z02

        det = (z11 + 1.0) * (z22 + 1.0) - (z12 * z21)
        inv_00 = (z22 + 1.0) / det
        inv_01 = -z12 / det
        inv_10 = -z21 / det
        inv_11 = (z11 + 1.0) / det

        S = np.zeros_like(Z, dtype=complex)
        S[:, 0, 0] = (z11 - 1.0) * inv_00 + z12 * inv_10
        S[:, 0, 1] = (z11 - 1.0) * inv_01 + z12 * inv_11
        S[:, 1, 0] = z21 * inv_00 + (z22 - 1.0) * inv_10
        S[:, 1, 1] = z21 * inv_01 + (z22 - 1.0) * inv_11
        return S

    #------------------------------------------------------------
    # General N-Port LAPACK Fallback (N >= 3)
    #------------------------------------------------------------
    I = np.eye(N)
    inv_sqrt_Z0 = np.diag(1.0 / np.sqrt(Z0_arr))

    # Normalize Z matrix: z = inv_sqrt(Z0) * Z * inv_sqrt(Z0)
    z_norm = np.matmul(np.matmul(inv_sqrt_Z0, Z), inv_sqrt_Z0)

    mat_inv = np.linalg.inv(z_norm + I)
    return np.matmul(z_norm - I, mat_inv)

def S_to_Y(S, Z0=50):
    """Converts general (Nf, N, N) S-parameters to Y-parameters supporting multi-Z0 arrays."""
    S = check(S)
    Nf, N, _ = S.shape

    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(N, Z0_arr[0])
    Y0_arr = 1.0 / Z0_arr

    #------------------------------------------------------------
    # 1-Port Vectorized Speed Override
    #------------------------------------------------------------
    if N == 1:
        S11 = S[:, 0, 0]
        Y_flat = Y0_arr[0] * (1.0 - S11) / (1.0 + S11)
        return Y_flat[:, np.newaxis, np.newaxis]

    #------------------------------------------------------------
    # 2-Port Vectorized Speed Override
    #------------------------------------------------------------
    elif N == 2:
        S11, S12, S21, S22 = S[:, 0, 0], S[:, 0, 1], S[:, 1, 0], S[:, 1, 1]
        Z01, Z02 = Z0_arr[0], Z0_arr[1]
        Y01, Y02 = Y0_arr[0], Y0_arr[1]

        det = (1.0 + S11) * (1.0 + S22) - (S12 * S21)
        inv_00 = (1.0 + S22) / det
        inv_01 = -S12 / det
        inv_10 = -S21 / det
        inv_11 = (1.0 + S11) / det

        Y = np.zeros_like(S, dtype=complex)
        Y[:, 0, 0] = Y01 * ((1.0 - S11) * inv_00 - S12 * inv_10)
        Y[:, 0, 1] = np.sqrt(Y01 * Y02) * ((1.0 - S11) * inv_01 - S12 * inv_11)
        Y[:, 1, 0] = np.sqrt(Y01 * Y02) * (-S21 * inv_00 + (1.0 - S22) * inv_10)
        Y[:, 1, 1] = Y02 * (-S21 * inv_01 + (1.0 - S22) * inv_11)
        return Y

    #------------------------------------------------------------
    # General N-Port LAPACK Fallback (N >= 3)
    #------------------------------------------------------------
    I = np.eye(N)
    mat_inv = np.linalg.inv(I + S)

    inv_sqrt_Z0 = np.diag(1.0 / np.sqrt(Z0_arr))
    temp = np.matmul(I - S, mat_inv)
    return np.matmul(np.matmul(inv_sqrt_Z0, temp), inv_sqrt_Z0)


def Y_to_S(Y, Z0=50):
    """Converts general (Nf, N, N) Y-parameters to S-parameters supporting multi-Z0 arrays."""
    Y = check(Y)
    Nf, N, _ = Y.shape

    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(N, Z0_arr[0])

    #------------------------------------------------------------
    # 1-Port Vectorized Speed Override
    #------------------------------------------------------------
    if N == 1:
        Y11 = Y[:, 0, 0]
        S_flat = (1.0 - Y11 * Z0_arr[0]) / (1.0 + Y11 * Z0_arr[0])
        return S_flat[:, np.newaxis, np.newaxis]

    #------------------------------------------------------------
    # 2-Port Vectorized Speed Override
    #------------------------------------------------------------
    elif N == 2:
        Y11, Y12, Y21, Y22 = Y[:, 0, 0], Y[:, 0, 1], Y[:, 1, 0], Y[:, 1, 1]
        Z01, Z02 = Z0_arr[0], Z0_arr[1]

        # Normalize Y components: y = sqrt(Z0) * Y * sqrt(Z0)
        y11 = Y11 * Z01
        y12 = Y12 * np.sqrt(Z01 * Z02)
        z21 = Y21 * np.sqrt(Z01 * Z02)  # Normalized tracking term
        y22 = Y22 * Z02

        det = (1.0 + y11) * (1.0 + y22) - (y12 * z21)
        inv_00 = (1.0 + y22) / det
        inv_01 = -y12 / det
        inv_10 = -z21 / det
        inv_11 = (1.0 + y11) / det

        S = np.zeros_like(Y, dtype=complex)
        S[:, 0, 0] = (1.0 - y11) * inv_00 - y12 * inv_10
        S[:, 0, 1] = (1.0 - y11) * inv_01 - y12 * inv_11
        S[:, 1, 0] = -z21 * inv_00 + (1.0 - y22) * inv_10
        S[:, 1, 1] = -z21 * inv_01 + (1.0 - y22) * inv_11
        return S

    #------------------------------------------------------------
    # General N-Port LAPACK Fallback (N >= 3)
    #------------------------------------------------------------
    I = np.eye(N)
    sqrt_Z0 = np.diag(np.sqrt(Z0_arr))

    # Normalize Y matrix: y_norm = sqrt(Z0) * Y * sqrt(Z0)
    y_norm = np.matmul(np.matmul(sqrt_Z0, Y), sqrt_Z0)

    mat_inv = np.linalg.inv(I + y_norm)
    return np.matmul(I - y_norm, mat_inv)

def S_to_ABCD(S, Z0=50):
    """Converts a batch of 2-port S-parameters with shape (Nf, 2, 2) to ABCD parameters supporting multi-Z0 arrays."""
    S = check(S, n=2)
    Nf = S.shape[0]

    # Handle Z0 array conversion [Z01, Z02]
    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(2, Z0_arr[0])
    Z01, Z02 = Z0_arr[0], Z0_arr[1]

    S11 = S[:, 0, 0]
    S12 = S[:, 0, 1]
    S21 = S[:, 1, 0]
    S22 = S[:, 1, 1]

    # Each element gets its own impedance-scaling factor (Frickey, 1994);
    # do NOT fold sqrt(Z01/Z02) into a shared denominator, it only cancels
    # correctly for A and silently corrupts B, C, D when Z01 != Z02.
    denom = 2.0 * S21
    ABCD = np.zeros((Nf, 2, 2), dtype=complex)

    ABCD[:, 0, 0] = (((1.0 + S11) * (1.0 - S22) + S12 * S21) / denom) * np.sqrt(Z01 / Z02)
    ABCD[:, 0, 1] = (((1.0 + S11) * (1.0 + S22) - S12 * S21) / denom) * np.sqrt(Z01 * Z02)
    ABCD[:, 1, 0] = (((1.0 - S11) * (1.0 - S22) - S12 * S21) / denom) / np.sqrt(Z01 * Z02)
    ABCD[:, 1, 1] = (((1.0 - S11) * (1.0 + S22) + S12 * S21) / denom) * np.sqrt(Z02 / Z01)

    return ABCD

def ABCD_to_S(ABCD, Z0=50):
    """Converts a batch of 2-port ABCD parameters with shape (Nf, 2, 2) to S-parameters supporting multi-Z0 arrays."""
    ABCD = check(ABCD, n=2)
    Nf = ABCD.shape[0]

    # Handle Z0 array conversion [Z01, Z02]
    Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
    if len(Z0_arr) == 1:
        Z0_arr = np.full(2, Z0_arr[0])
    Z01, Z02 = Z0_arr[0], Z0_arr[1]

    A = ABCD[:, 0, 0]
    B = ABCD[:, 0, 1]
    C = ABCD[:, 1, 0]
    D = ABCD[:, 1, 1]

    # The denominator generalized for multi-Z0
    denom = A * Z02 + B + C * Z01 * Z02 + D * Z01
    S = np.zeros((Nf, 2, 2), dtype=complex)

    S[:, 0, 0] = (A * Z02 + B - C * Z01 * Z02 - D * Z01) / denom
    S[:, 0, 1] = 2.0 * (A * D - B * C) * np.sqrt(Z01 * Z02) / denom
    S[:, 1, 0] = 2.0 * np.sqrt(Z01 * Z02) / denom
    S[:, 1, 1] = (-A * Z02 + B - C * Z01 * Z02 + D * Z01) / denom

    return S

