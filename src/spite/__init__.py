COLORMAPS = ["Blues_r",  "Oranges_r", "Greens_r","Reds_r", "Purples_r","Greys_r"]
STATIC_COLORS = ["C0", "C1", "C2", "C3", "C4", "C7"]

class Network:
    """The generic base class for all microwave networks (1-Port, 2-Port, N-Port)."""

    def __init__(self, f, S, Z0=50, schematic=np.array([[0]])):
        self.f = np.asarray(f)
        self.S = np.asarray(S)
        self.Nports = self.S.shape[1] # Automatically infer number of ports

        # Normalize Z0 into a 1D array of length equal to the number of ports
        Z0_arr = np.atleast_1d(np.asarray(Z0, dtype=float))
        if len(Z0_arr) == 1:
            self.Z0 = np.full(self.Nports, Z0_arr[0])
        elif len(Z0_arr) == self.Nports:
            self.Z0 = Z0_arr
        else:
            raise ValueError(f"Z0 length ({len(Z0_arr)}) must match the number of ports ({self.ports}).")

        # Handle default schematic (Black box square)
        if schematic is None:
            schematic = np.zeros((DEFAULT_HEIGHT, DEFAULT_HEIGHT), dtype=int)
        elif schematic.shape[0] != DEFAULT_HEIGHT:
            schematic = resize_schematic(schematic, new_height=DEFAULT_HEIGHT)

        self.schematic = np.asarray(schematic)

    @property
    def Z(self):
        """Computes and returns Z-parameters."""
        return S_to_Z(self.S, self.Z0)

    @property
    def Y(self):
        """Computes and returns Y-parameters."""
        return S_to_Y(self.S, self.Z0)

    def plot_schematic(self, figsize=DEFAULT_FIGSIZE, cmap="gray"):
        """Renders the 2D visual schematic bitmap of this network."""


        return plot_schematic(self.schematic, figsize=figsize, cmap=cmap)

    def _prepare_plot_data(self, param="S", port_indices=(1, 1)):
        """Helper to extract frequencies, sampled parameter, and legend label."""
        if len(port_indices) != 2:
            raise ValueError("`port_indices` must be a tuple of two 1-based port indices, e.g., (1, 1) or (2, 1).")

        # Pull parameters across all frequencies using sample engine
        val = self.sample(self.f, param=param, port_indices=port_indices)
        label = f"${param}_{{{port_indices[0]}{port_indices[1]}}}$"
        return self.f, val, label

    def _parse_ports(self, port_indices):
        """Standardizes port input into a list and returns whether it was a single raw tuple."""
        is_raw_tuple = isinstance(port_indices, tuple) and len(port_indices) == 2 and isinstance(port_indices[0], int)

        if is_raw_tuple:
            port_list = [port_indices]
        elif isinstance(port_indices, (list, tuple)):
            port_list = list(port_indices)
        else:
            raise ValueError("`port_indices` must be a tuple like (1, 1) or a list/tuple like [(1, 1), (2, 1)].")

        if len(port_list) > 6:
            raise ValueError(f"Maximum 6 port pairs allowed for simultaneous plotting, got {len(port_list)}.")

        return port_list, is_raw_tuple

    def plot_lin(self, param="S", port_indices=(1, 1), cmap="plasma", ax=None):
        """Plots parameter magnitude in dB vs frequency."""
        ports, is_raw_tuple = self._parse_ports(port_indices)

        if ax is None:
            fig, ax = plt.subplots(figsize=(8, 5))

        if is_raw_tuple:
            # --- 1. SINGLE RAW TUPLE (1, 1) ->  GRADIENT ---
            p = ports[0]
            f, val, label = self._prepare_plot_data(param=param, port_indices=p)
            mag = np.abs(val)

            norm = plt.Normalize(vmin=f[0], vmax=f[-1])
            color_map = plt.colormaps[cmap]

            for i in range(len(f) - 1):
                c = color_map(norm(f[i]))
                ax.plot(f[i:i+2] / 1e9, mag[i:i+2], color=c, lw=2)

            ax.set_ylabel(f"|{label}| (dB)")
            ax.set_title(f"Magnitude Response of {label} (dB)")

            # Frequency Colorbar
            sm = plt.cm.ScalarMappable(cmap=color_map, norm=norm)
            sm.set_array([])
            cbar = plt.colorbar(sm, ax=ax)
            cbar.set_label("Frequency (Hz)")

        else:
            # --- 2. ARRAY OF PORTS [(1,1), ...] -> STATIC COLORS ---
            for idx, p in enumerate(ports):
                f, val, label = self._prepare_plot_data(param=param, port_indices=p)
                mag = np.abs(val)

                # One solid plot call per port pair (fast & clean)
                ax.plot(f / 1e9, mag, color=STATIC_COLORS[idx], lw=2, label=label)

            ax.set_ylabel(f"|{param}| (dB)")
            ax.set_title(f"Magnitude Response ({param}-Parameters in dB)")
            ax.legend(loc="upper right", frameon=True)

        ax.set_xlabel("Frequency (GHz)")
        ax.grid(True, linestyle="--", alpha=0.6)

        return ax

    def plot_dB(self, floor=-40, param="S", port_indices=(1, 1), cmap="plasma", ax=None):
        """Plots parameter magnitude in dB vs frequency."""
        ports, is_raw_tuple = self._parse_ports(port_indices)

        if ax is None:
            fig, ax = plt.subplots(figsize=(8, 5))

        if is_raw_tuple:
            # --- 1. SINGLE RAW TUPLE (1, 1) -> GRADIENT ---
            p = ports[0]
            f, val, label = self._prepare_plot_data(param=param, port_indices=p)
            mag_db = 20 * np.log10(np.maximum(np.abs(val), 10**(floor / 20)))

            norm = plt.Normalize(vmin=f[0], vmax=f[-1])
            color_map = plt.colormaps[cmap]

            for i in range(len(f) - 1):
                c = color_map(norm(f[i]))
                ax.plot(f[i:i+2] / 1e9, mag_db[i:i+2], color=c, lw=2)

            ax.set_ylabel(f"|{label}| (dB)")
            ax.set_title(f"Magnitude Response of {label} (dB)")

        else:
            # --- 2. ARRAY OF PORTS [(1,1), ...] -> STATIC COLORS ---
            for idx, p in enumerate(ports):
                f, val, label = self._prepare_plot_data(param=param, port_indices=p)
                mag_db = 20 * np.log10(np.maximum(np.abs(val), 10**(floor / 20)))

                # One solid plot call per port pair (fast & clean)
                ax.plot(f / 1e9, mag_db, color=STATIC_COLORS[idx], lw=2, label=label)

            ax.set_ylabel(f"|{param}| (dB)")
            ax.set_title(f"Magnitude Response ({param}-Parameters in dB)")
            ax.legend(loc="upper right", frameon=True)

        ax.set_xlabel("Frequency (GHz)")
        ax.grid(True, linestyle="--", alpha=0.6)

        return ax

    def _draw_smith_chart(self, ax=None, r_vals=None, x_vals=None, chart_type="Z"):
        if ax is None:
            ax = plt.gca()

        if r_vals is None:
            r_vals = [0, 0.2, 0.5, 1, 2, 5, 20]
        if x_vals is None:
            x_vals = [0, 0.2, 0.5, 1, 2, 5, 20]

        # A Y-chart (admittance) is a Z-chart (impedance) reflected through the
        # origin: Gamma_Y = -Gamma_Z. Everything below is identical to the Z-chart
        # geometry, just multiplied by `sign`.
        sign = 1 if chart_type == "Z" else -1

        # Outer unit circle (|Gamma| = 1) -- symmetric about the origin, unaffected by sign
        theta = np.linspace(0, 2 * np.pi, 500)
        ax.plot(np.cos(theta), np.sin(theta), color='black', lw=1.5)

        # 1. Constant Resistance / Conductance Circles
        x_samp = np.linspace(-100, 100, 2000)
        for r in r_vals:
            z = r + 1j * x_samp
            gamma = sign * (z - 1) / (z + 1)
            mask = np.abs(gamma) <= 1.001
            ax.plot(gamma.real[mask], gamma.imag[mask], color='gray', lw=0.7, ls='--')

            if r != 0:  # r=0 coincides with the outer boundary itself, skip to avoid clutter
                gamma_label = sign * (r - 1) / (r + 1)
                ax.text(gamma_label, 0.02, f"{r:g}", fontsize=7, color='black',
                        ha='center', va='bottom')

        # 2. Constant Reactance / Susceptance Arcs
        r_samp = np.linspace(0, 100, 1000)
        for x in x_vals:
            if x == 0:
                # Real axis line
                ax.plot([-1, 1], [0, 0], color='gray', lw=0.8, ls='--')

                # Label '0' at the short-circuit / open-circuit edge on the outer perimeter
                # For Z-chart: Left edge (-1, 0) | For Y-chart: Right edge (+1, 0)
                zero_edge = sign * (-1.08)
                ax.text(zero_edge, 0, "0", fontsize=7, color='black', ha='center', va='center')
                continue

            for arc_sign in [+1, -1]:
                z = r_samp + 1j * (arc_sign * x)
                gamma = sign * (z - 1) / (z + 1)
                mask = np.abs(gamma) <= 1.001
                ax.plot(gamma.real[mask], gamma.imag[mask], color='gray', lw=0.7, ls='--')

                z_edge = 0 + 1j * (arc_sign * x)
                g_edge = sign * (z_edge - 1) / (z_edge + 1)
                label_pos = g_edge * 1.08
                sign_str = "+" if arc_sign > 0 else "-"
                ax.text(label_pos.real, label_pos.imag, f"{sign_str}j{x:g}",
                        fontsize=7, color='black', ha='center', va='center')

        ax.set_aspect('equal')
        ax.axis('off')

    def plot_smith(self, port_indices=(1, 1), chart_type="Z", cmap="plasma", ax=None):
        if ax is None:
            fig, ax = plt.subplots()

        ports, is_raw_tuple = self._parse_ports(port_indices)
        self._draw_smith_chart(ax=ax, r_vals=[0, 0.2, 0.5, 1, 2, 5, 20], chart_type=chart_type)

        if is_raw_tuple:
            cmaps = [cmap]
            frac = 1.0
        else:
            cmaps = COLORMAPS
            frac = 0.8

        for idx, p in enumerate(ports):
            p1, p2 = p
            val = self.sample(self.f, param="S", port_indices=p)

            c_map = plt.get_cmap(cmaps[idx % len(cmaps)])
            colors = c_map(np.linspace(0, frac, len(val)))

            lw = 2.5 - (idx * 0.4)
            ax.plot([], [], color=colors[0], lw=lw, label=f"$S_{{{p1}{p2}}}$")

            for i in range(len(val) - 1):
                ax.plot(val.real[i:i+2], val.imag[i:i+2], color=colors[i], lw=lw)

        # 4. One colorbar per plotted trace  <-- now at the SAME indent level as the loop above it, not inside it
        for idx, p in enumerate(ports):
            cbar_cmap_name = cmap if is_raw_tuple else cmaps[idx % len(cmaps)]
            display_cmap = plt.matplotlib.colors.LinearSegmentedColormap.from_list(
                "smith_freq_cbar", plt.get_cmap(cbar_cmap_name)(np.linspace(0, frac, 256))
            )
            norm = plt.Normalize(vmin=self.f[0] / 1e9, vmax=self.f[-1] / 1e9)
            sm = plt.cm.ScalarMappable(cmap=display_cmap, norm=norm)
            sm.set_array([])
            cbar = plt.colorbar(sm, ax=ax, fraction=0.046, pad=0.04)

            is_outermost = (idx == 0)
            if is_outermost:
                cbar.set_label("Frequency (GHz)", rotation=270, labelpad=15)
            else:
                cbar.ax.tick_params(labelright=False, right=False)

        if is_raw_tuple:
            p1, p2 = ports[0]
            if chart_type == "Z":
                ax.set_title(f"$S_{{{p1}{p2}}}$ [Impedance View]")
            elif chart_type == "Y":
                ax.set_title(f"$S_{{{p1}{p2}}}$ [Admittance View]")
            else:
                raise ValueError(f"Invalid Chart Type: {chart_type!r}")
        else:
            ax.legend(loc="upper right", frameon=True)
            if chart_type == "Z":
                ax.set_title(f"S-Parameters [Impedance View]")
            elif chart_type == "Y":
                ax.set_title(f"S-Parameters [Admittance View]")
            else:
                raise ValueError(f"Invalid Chart Type: {chart_type!r}")

        return ax

    def sample(self, f_eval, param="S", port_indices=None):
        if f_eval is None:
            f_eval = self.f
        f_eval_arr = np.atleast_1d(np.asarray(f_eval, dtype=float))

        # Check bounds
        if np.any(f_eval_arr < self.f[0]) or np.any(f_eval_arr > self.f[-1]):
            print(f"Warning: Frequencies out of bounds [{self.f[0]/1e9:.2f}, {self.f[-1]/1e9:.2f}] GHz. Clipping.")
            f_eval_arr = np.clip(f_eval_arr, self.f[0], self.f[-1])

        match param:
            case "S": full_matrix = self.S
            case "Z": full_matrix = self.Z
            case "Y": full_matrix = self.Y
            case "ABCD":
                if self.Nports != 2:
                    raise ValueError(
                        f"ABCD parameters are strictly defined for 2-port networks. "
                        f"Current network has {self.Nports} ports."
                    )
                full_matrix = self.ABCD
            case _: raise ValueError(f"Invalid Parameter Type: {param!r}")

        # Allocate matrix with shape (N_freqs, ports, ports)
        N_pts = len(f_eval_arr)
        interp_matrix = np.zeros((N_pts, self.Nports, self.Nports), dtype=complex)

        for i in range(self.Nports):
            for j in range(self.Nports):
                real_part = np.interp(f_eval_arr, self.f, full_matrix[:, i, j].real)
                imag_part = np.interp(f_eval_arr, self.f, full_matrix[:, i, j].imag)
                interp_matrix[:, i, j] = real_part + 1j * imag_part

        # 1. Slice specific port first (if requested)
        if port_indices is not None:
            i, j = port_indices[0] - 1, port_indices[1] - 1
            interp_matrix = interp_matrix[:, i, j]

        # 2. Collapse the frequency dimension ONLY if the caller passed a scalar float/int
        if np.isscalar(f_eval):
            return interp_matrix[0]

        return interp_matrix

    @staticmethod
    def _tukey_window(N, alpha=0.05):
        """Tukey (tapered cosine) window, implemented directly with NumPy
        (no scipy dependency) to match SPITE's single-file philosophy."""
        if alpha <= 0:
            return np.ones(N)
        if alpha >= 1:
            return np.hanning(N)
        n = np.arange(N)
        w = np.ones(N)
        edge = int(alpha * (N - 1) / 2.0)
        w[:edge + 1] = 0.5 * (1 + np.cos(np.pi * (2 * n[:edge + 1] / (alpha * (N - 1)) - 1)))
        w[N - edge - 1:] = w[:edge + 1][::-1]
        return w

    def _time_axis(self):
        """Shared time-axis construction for gate() and plot_time_domain().
        Requires uniformly spaced frequency samples."""
        df = np.diff(self.f)
        if not np.allclose(df, df[0], rtol=1e-6):
            raise ValueError("This operation requires uniformly spaced frequency samples.")
        Nf = len(self.f)
        fs = df[0] * Nf
        t = np.arange(Nf) / fs
        return t, fs


    def gate(self, t_start, t_stop, alpha=0.05, trim=True):
        """
        Time-domain gate on S: transforms S(f) to the time domain, zeroes out
        everything outside [t_start, t_stop] (seconds), and transforms back.
        Used to strip out delayed reflections (e.g. cable/connector echoes)
        that show up at a different time delay than the actual DUT response.
        """
        t, fs = self._time_axis()
        Nf = len(self.f)

        W = self._tukey_window(Nf, alpha)
        S_win = self.S * W[:, None, None]
        s_t = np.fft.ifft(S_win, axis=0)

        gate_mask = (t >= t_start) & (t <= t_stop)
        s_t_gated = s_t * gate_mask[:, None, None]

        W_floor = np.maximum(W, 0.05 * W.max())
        S_gated = np.fft.fft(s_t_gated, axis=0) / W_floor[:, None, None]

        f_out, S_out = self.f, S_gated
        if trim:
            flat_mask = (W == 1.0)
            if not np.any(flat_mask):
                raise ValueError("trim=True removed every frequency point -- try a smaller alpha.")
            f_out = self.f[flat_mask]
            S_out = S_gated[flat_mask]

        return self.__class__(f_out, S_out, Z0=self.Z0)


