def plot_schematic(schematic, figsize=DEFAULT_FIGSIZE, cmap="gray"):
    """
    Renders a bitmap using a configurable global figure size and cmap.
    """

    fig, ax = plt.subplots(figsize=figsize)
    ax.imshow(schematic, cmap=cmap, interpolation='nearest')
    ax.axis('off')
    plt.tight_layout()

    return fig, ax

def resize_schematic(schematic, new_height= DEFAULT_HEIGHT):
    """
    Resizes a binary schematic matrix using pure NumPy nearest-neighbor scaling.
    Preserves exact aspect ratio and binary {0, 1} pixel values without SciPy.
    """
    old_height, old_width = schematic.shape

    # Calculate target width to keep exact aspect ratio
    scale_factor = new_height / old_height
    new_width = int(round(old_width * scale_factor))

    # Map output row and column indices back to the original array coordinates
    row_indices = np.floor(np.linspace(0, old_height, new_height, endpoint=False)).astype(int)
    col_indices = np.floor(np.linspace(0, old_width, new_width, endpoint=False)).astype(int)

    # 2D advanced indexing to construct the new array instantly
    return schematic[row_indices[:, None], col_indices]

